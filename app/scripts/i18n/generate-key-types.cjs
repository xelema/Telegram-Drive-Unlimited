const fs = require('fs');
const path = require('path');
const { loadLocale } = require('./shared.cjs');

const OUTPUT_FILE = path.join(__dirname, '../../src/i18n/translationKeys.generated.ts');

function generateKeyTypes(checkMode = false) {
  const en = loadLocale('en');
  const keys = Object.keys(en.flat).sort();

  const code = `// DO NOT EDIT DIRECTLY. Generated by scripts/i18n/generate-key-types.cjs

export type TranslationKey =
${keys.map(k => `  | '${k}'`).join('\n')};

export type TranslationDomain =
  | 'common'
  | 'auth'
  | 'navigation'
  | 'files'
  | 'folders'
  | 'transfers'
  | 'preview'
  | 'media'
  | 'archive'
  | 'share'
  | 'settings'
  | 'network'
  | 'updates'
  | 'errors'
  | 'ads'
  | 'accessibility';
`;

  if (checkMode) {
    if (!fs.existsSync(OUTPUT_FILE)) {
      console.error(`[FAIL] Translation keys file does not exist: ${OUTPUT_FILE}`);
      process.exit(1);
    }
    const current = fs.readFileSync(OUTPUT_FILE, 'utf8');
    if (current !== code) {
      console.error('[FAIL] translationKeys.generated.ts is out of date. Run "npm run i18n:types" locally.');
      process.exit(1);
    }
    console.log('[PASS] translationKeys.generated.ts is up to date.');
  } else {
    fs.writeFileSync(OUTPUT_FILE, code, 'utf8');
    console.log(`[PASS] Generated ${keys.length} typed translation keys in ${path.basename(OUTPUT_FILE)}`);
  }
}

const checkMode = process.argv.includes('--check');
generateKeyTypes(checkMode);
